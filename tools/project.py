def utc() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def append_ledger(row: dict) -> None:
    LEDGER.parent.mkdir(parents=True, exist_ok=True)
    with LEDGER.open("a", encoding="utf-8", newline="\n") as stream:
        stream.write(json.dumps(row, sort_keys=True) + "\n")


def read_ledger() -> list[dict]:
    if not LEDGER.is_file():
        return []
    rows = []
    for line in LEDGER.read_text(encoding="utf-8", errors="replace").splitlines():
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return rows


def gate_checks() -> list[tuple[str, bool, str]]:
    checks: list[tuple[str, bool, str]] = []
    tests = subprocess.run(
        [sys.executable, "-m", "unittest", "discover", "-s", "tests", "-v"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    checks.append(("unit tests", tests.returncode == 0, (tests.stdout + tests.stderr).strip()[-4000:]))
    compiled = subprocess.run(
        [sys.executable, "-m", "compileall", "-q", "forge", "blender", "tools", "tests"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    checks.append(("python compileall", compiled.returncode == 0, (compiled.stdout + compiled.stderr).strip()[-2000:]))
    forbidden = subprocess.run(
        ["rg", "-n", "-i", r"kv3|keyvalues3|kv3-parser", "forge", "blender", "tests", "--glob", "!__pycache__/**"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    # The gate's own negative control names the forbidden parser; the source
    # scan deliberately excludes tools/project.py so the control can exist.
    checks.append((
        "no KV3 parser in source",
        forbidden.returncode in (1, 2) or not forbidden.stdout.strip(),
        forbidden.stdout[-2000:],
    ))
    boundary = subprocess.run(
        [
            "rg",
            "-n",
            r"vmdl[^\n]*(write|open)|open\([^\n]*vmdl[^\n]*['\"]w",
            "forge",
            "--glob",
            "!__pycache__/**",
            "--glob",
            "!migrate.py",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    checks.append((
        "no vmdl writes in forge",
        boundary.returncode in (1, 2) or not boundary.stdout.strip(),
        boundary.stdout[-2000:],
    ))
    dependency = subprocess.run(
        [sys.executable, "-c", "import blake3; print(blake3.blake3(b'x').hexdigest())"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    checks.append((
        "blake3 dependency",
        dependency.returncode == 0
        and dependency.stdout.strip()
        == "3ae7d805f6789a6402acb70ad4096a85a56bf6804eaf25c0493ac697548d30b5",
        (dependency.stdout + dependency.stderr).strip()[-2000:],
    ))
    return checks


def write_status(checks: list[tuple[str, bool, str]]) -> None:
    rows = read_ledger()
    compile_rows = [row for row in rows if row.get("command") == "compile"]
    last_compile = compile_rows[-1] if compile_rows else None
    lines = [
        "# Status",
        "",
        "Generated by `python tools/project.py gate`. Do not hand-edit.",
        "",
        f"Updated: {utc()}",
        "",
        "## Gate",
        "",
    ]
    for name, ok, detail in checks:
        lines.append(f"- [{'x' if ok else ' '}] {name}" + (f" — {detail.splitlines()[-1]}" if not ok and detail else ""))
    lines.extend(
        [
            "",
            "## Surface",
            "",
            "- Blender 5.4 addon: hero picker, custom model import, collection-scoped parts, per-slot material assignment, fit, split compare, bone map, manual rename/alignment, HYBRID/CUSTOM/ENVELOPE retarget, Axis proof, stage, compile.",
            "- Live game build: read from `game/citadel/steam.inf` at run time.",
            "- S2V: hero inventory and extraction; vmdl is copied byte-for-byte.",
            "- CSDK13: stage and compile install into `content/citadel_addons/<addon>` and `game/citadel_addons/<addon>` in the CSDK root.",
            "- Proof identity: BLAKE3; SHA-256 remains as legacy stage evidence.",
            "- CSDK13 compile: in place in the content addon; compiled `_c` files stay in the game addon.",
            "- Old addon migration: general old VPK/folder import, automatic cloth/physics section discovery and exact transplant, optional explicit old vmdl selection, custom model/material preservation, and live-model update.",
            "",
            "## Observed evidence",
            "",
        ]
    )
    if last_compile:
        output = last_compile.get("output") or "no output copied"
        lines.append(
            f"- CSDK13 compile: `{last_compile.get('result', 'unknown')}` (return code {last_compile.get('returncode', '?')}); output `{output}`."
        )
        if last_compile.get("warnings") is not None:
            lines.append(f"- Compiler warnings: {last_compile['warnings']}.")
    else:
        lines.append("- CSDK13 compile: not yet recorded.")
    latest_import = next((row for row in reversed(rows) if row.get("command") == "blender-import"), None)
    if latest_import:
        lines.append(f"- Blender import: {latest_import.get('observed', 'recorded')}")
    latest_real = next((row for row in reversed(rows) if row.get("command") == "real-mesh"), None)
    if latest_real:
        lines.append(f"- Real mesh: {latest_real.get('observed', 'recorded')}")
    latest_workbench = next(
        (row for row in reversed(rows) if "blender_workbench_probe.py" in str(row.get("command", ""))),
        None,
    )
    if latest_workbench:
        lines.append(f"- Workbench probe: `{latest_workbench.get('result', 'unknown')}`; {latest_workbench.get('observed', 'recorded')}")
    updates = [row for row in rows if row.get("command") == "update-addon"]
    latest_update = max(
        updates,
        key=lambda row: (row.get("cloth_chains", 0), row.get("materials", 0)),
        default=None,
    )
    if latest_update:
        lines.append(
            "- Old addon migration: `"
            f"{latest_update.get('result', 'unknown')}`; {latest_update.get('model_files', 0)} old model files, "
            f"{latest_update.get('materials', 0)} old material assets, "
            f"{latest_update.get('cloth_chains', 0)} cloth chains, {latest_update.get('cloth_hinges', 0)} hinges."
        )
    latest_zip = next(
        (row for row in reversed(rows) if "blender_zip_probe.py" in str(row.get("command", ""))),
        None,
    )
    if latest_zip:
        lines.append(f"- Installable zip: `{latest_zip.get('result', 'unknown')}`; {latest_zip.get('observed', 'recorded')}")
    lines.extend(
        [
            "",
            "## Boundaries",
            "",
            "- No KV3 parser.",
            "- No vmdl reconstruction, metadata extraction, or vmdl rewriting except the named old-addon migration that transplants old top-level sections.",
            "- The selected DMX and its LOD DMXs are replaced; materials are copied verbatim.",
            "",
        ]
    )
    STATUS.write_text("\n".join(lines), encoding="utf-8")


def cmd_doctor(args: argparse.Namespace) -> int:
    env = detect()
    for name, value in env.summary():
        print(f"{name:18} {value}")
    if env.problems:
        print("\nProblems:")
        for problem in env.problems:
            print(f"- {problem}")
    print("\nAxis presets:")
    for name in PRESETS:
        transform = AxisTransform.preset(name, allow_mirror=(name == "mirror-x"))
        print(f"- {name:20} det={transform.determinant:+d} {transform.matrix}")
    return 0 if env.game_root and env.s2v else 1


def cmd_heroes(args: argparse.Namespace) -> int:
    env = detect()
    try:
        heroes = list_heroes(env)
    except LiveError as error:
        print(error, file=sys.stderr)
        return 2
    for hero in heroes:
        print(f"{hero.slug:24} {hero.model_path}")
    print(f"\n{len(heroes)} heroes")
    append_ledger({"at": utc(), "command": "heroes", "result": "pass", "observed": f"{len(heroes)} live heroes"})
    return 0


def cmd_extract(args: argparse.Namespace) -> int:
    env = detect()
    try:
        heroes = list_heroes(env)
        hero = next((item for item in heroes if item.slug.lower() == args.hero.lower()), None)
        if hero is None:
            print(f"hero-not-found: {args.hero}", file=sys.stderr)
            return 2
        result = extract(env, hero, Path(args.out), force=args.force)
    except LiveError as error:
        print(error, file=sys.stderr)
        return 2
    print(f"root {result.root}")
    print(f"vmdl {result.vmdl or 'NOT EMITTED BY S2V CLI'}")
    print(f"body {result.body_dmx or 'none'}")
    print(f"dmx {len(result.dmx_files)} gltf {len(result.gltf_files)} vmat {len(result.material_files)}")
    if result.log:
        print(f"log {result.log}")
    append_ledger(
        {
            "at": utc(),
            "command": "extract",
            "result": "pass" if result.vmdl and result.body_dmx else "partial",
            "hero": args.hero,
            "vmdl": str(result.vmdl) if result.vmdl else "",
            "body_dmx": str(result.body_dmx) if result.body_dmx else "",
            "dmx_files": len(result.dmx_files),
            "vmat_files": len(result.material_files),
        }
    )
    return 0 if result.vmdl and result.body_dmx else 3


def _materials_root(value: str) -> list[MaterialCopy]:
    if not value:
        return []
    root = Path(value)
    if not root.is_dir():
        raise SystemExit(f"--materials-root is not a directory: {value}")
    return material_files(root)


def _material_specs(values: list[str]) -> list[MaterialCopy]:
    result = []
    for value in values:
        if ":" not in value:
            raise SystemExit(f"--material wants source:relative, got {value!r}")
        source, relative = value.split(":", 1)
        result.append(MaterialCopy(Path(source), relative))
    return result


def cmd_stage(args: argparse.Namespace) -> int:
    request = StageRequest(
        extraction_root=Path(args.extraction),
        vmdl=Path(args.vmdl),
        target_dmx=Path(args.target_dmx),
        custom_dmx=Path(args.custom_dmx),
        target_dmx_relative=args.target_dmx_relative,
        vmdl_relative=args.vmdl_relative,
        addon_name=args.addon,
        destination=Path(args.out),
        materials=_materials_root(args.materials_root) if args.materials_root else _material_specs(args.material or []),
        custom_materials=(
            _materials_root(args.custom_materials_root)
            if args.custom_materials_root
            else []
        ),
        custom_lods=[Path(path) for path in (args.custom_lod or [])],
    )
    try:
        result = stage(request)
        verify(result)
    except (StageError, OSError) as error:
        print(f"stage-failed: {error}", file=sys.stderr)
        return 2
    print(f"staged {result.root}")
    print(f"vmdl {result.vmdl} sha256={result.vmdl_sha256} blake3={result.vmdl_blake3} modified=false")
    print(f"custom {result.custom_dmx} sha256={result.custom_sha256} blake3={result.custom_blake3}")
    print(f"lods {len(result.custom_lods)}")
    print(
        "materials "
        f"{result.material_count} ({result.material_texture_count} textures) "
        f"custom_materials {result.custom_material_count} "
        f"({result.custom_material_texture_count} textures)"
    )
    append_ledger(
        {
            "at": utc(),
            "command": "stage",
            "result": "pass",
            "stage": str(result.root),
            "vmdl_sha256": result.vmdl_sha256,
            "vmdl_blake3": result.vmdl_blake3,
            "custom_sha256": result.custom_sha256,
            "custom_blake3": result.custom_blake3,
            "lods": len(result.custom_lods),
            "materials": result.material_count,
            "material_textures": result.material_texture_count,
            "custom_materials": result.custom_material_count,
            "custom_material_textures": result.custom_material_texture_count,
        }
    )
    return 0


def cmd_compile(args: argparse.Namespace) -> int:
    env = detect()
    try:
        if args.stage:
            result = compile_stage(
                env,
                Path(args.stage),
                args.addon,
                log_path=Path(args.log),
            )
        else:
            result = compile_vmdl(env, Path(args.vmdl), log_path=Path(args.log))
    except (CompileError, OSError, subprocess.TimeoutExpired) as error:
        print(f"compile-failed: {error}", file=sys.stderr)
        return 2
    print(f"returncode {result.returncode}")
    print(f"log {result.log}")
    print(f"compiled_files {len(result.compiled_files)}")
    if result.output:
        print(f"output {result.output}")
    warnings = len(re.findall(r"RESOURCE COMPILE WARNING:", result.stdout + result.stderr))
    if args.report:
        report = Path(args.report)
        data = json.loads(report.read_text(encoding="utf-8")) if report.is_file() else {"ports": []}
        matched = False
        for entry in data.get("ports", []):
            if entry.get("addon") != (args.addon or ""):
                continue
            matched = True
            entry["compile"] = {
                "returncode": result.returncode,
                "compiled_files": [str(path) for path in result.compiled_files],
                "output": str(result.output) if result.output else "",
                "warnings": warnings,
                "log": str(result.log),
                "errors": re.findall(r"RESOURCE COMPILE ERROR: (.+)", result.stdout + result.stderr)[:12],
            }
        if matched:
            report.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
            print(f"receipt {report}")
    append_ledger(
        {
            "at": utc(),
            "command": "compile",
            "result": "pass" if result.returncode == 0 else "fail",
            "returncode": result.returncode,
            "argv": result.command,
            "warnings": warnings,
            "stage": args.stage or "",
            "addon": args.addon or "",
            "log": str(result.log),
            "output": str(result.output) if result.output else "",
            "compiled_files": [str(path) for path in result.compiled_files],
            "content_addon": str(result.content_addon) if result.content_addon else "",
            "game_addon": str(result.game_addon) if result.game_addon else "",
        }
    )
    if result.returncode != 0:
        print((result.stdout + "\n" + result.stderr)[-4000:], file=sys.stderr)
    return 0 if result.returncode == 0 else result.returncode


def cmd_update_addon(args: argparse.Namespace) -> int:
    env = detect()
    source = Path(args.source).expanduser()
    hero = None
    if args.hero:
        try:
            heroes = list_heroes(env)
        except LiveError as error:
            print(f"update-addon-failed: {error}", file=sys.stderr)
            return 2
        hero = next((item for item in heroes if item.slug.lower() == args.hero.lower()), None)
        if hero is None:
            print(f"hero-not-found: {args.hero}", file=sys.stderr)
            return 2
    if hero is None and not args.new_extraction:
        print("update-addon-failed: --hero or --new-extraction is required", file=sys.stderr)
        return 2
    addon = args.addon.strip() or f"{source.stem}_updated"
    sections = tuple(args.preserve_section) if args.preserve_section else None
    try:
        result = update_from_package(
            env,
            source,
            Path(args.out),
            addon,
            hero=hero,
            new_extraction=Path(args.new_extraction) if args.new_extraction else None,
            new_vmdl=Path(args.new_vmdl) if args.new_vmdl else None,
            old_vmdl=Path(args.old_vmdl) if args.old_vmdl else None,
            preserve_model=args.model,
            preserve_materials=not args.no_materials,
            sections=sections,
            force=args.force,
        )
    except (MigrationError, LiveError, OSError, subprocess.TimeoutExpired) as error:
        print(f"update-addon-failed: {error}", file=sys.stderr)
        return 2
    print(f"updated {result.root}")
    print(f"vmdl {result.vmdl} sha256={digest(result.vmdl)}")
    print(f"old_vmdl {result.old_vmdl}")
    print(f"new_vmdl {result.new_vmdl}")
    print(f"preserved_model {result.preserved_model} model_files {len(result.model_files)} materials {result.material_count} textures {result.material_texture_count}")
    for name, action in result.sections.items():
        print(f"section {name} {action['action']} old={action.get('old_sha256','')[:12]} out={action.get('output_sha256','')[:12]}")
    manifest = json.loads(result.manifest.read_text(encoding="utf-8"))
    print(f"cloth_chains {manifest.get('cloth_chains', 0)} cloth_hinges {manifest.get('cloth_hinges', 0)}")
    if args.report:
        report = Path(args.report)
        existing = json.loads(report.read_text(encoding="utf-8")) if report.is_file() else {"ports": []}
        entry = {
            "ported_at": utc(),
            "source": str(source),
            "addon": addon,
            "output": str(result.root),
            "vmdl_sha256": manifest.get("vmdl_sha256", ""),
            "old_package": manifest.get("old_package", ""),
            "old_vmdl": manifest.get("old_vmdl", ""),
            "old_vmdl_sha256": manifest.get("old_vmdl_sha256", ""),
            "new_vmdl": manifest.get("new_vmdl", ""),
            "preserved_model": result.preserved_model,
            "model_files": len(result.model_files),
            "materials": result.material_count,
            "material_textures": result.material_texture_count,
            "sections": result.sections,
            "cloth_chains": manifest.get("cloth_chains", 0),
            "cloth_hinges": manifest.get("cloth_hinges", 0),
            "missing_sections": manifest.get("missing_sections", []),
        }
        ports = [item for item in existing.get("ports", []) if item.get("addon") != addon]
        ports.append(entry)
        report.parent.mkdir(parents=True, exist_ok=True)
        report.write_text(json.dumps({"ports": ports}, indent=2) + "\n", encoding="utf-8")
        print(f"receipt {report}")
    append_ledger(
        {
            "at": utc(),
            "command": "update-addon",
            "result": "pass",
            "source": str(source),
            "addon": addon,
            "output": str(result.root),
            "old_vmdl": str(result.old_vmdl),
            "new_vmdl": str(result.new_vmdl),
            "vmdl_sha256": manifest.get("vmdl_sha256", ""),
            "preserved_model": result.preserved_model,
            "model_files": len(result.model_files),
            "materials": result.material_count,
            "material_textures": result.material_texture_count,
            "sections": result.sections,
            "cloth_chains": manifest.get("cloth_chains", 0),
            "cloth_hinges": manifest.get("cloth_hinges", 0),
        }
    )
    if args.compile:
        log_path = ROOT / "logs" / "update-addon-compile.log"
        try:
            compiled = compile_stage(env, Path(args.out), addon, log_path=log_path)
        except (CompileError, OSError, subprocess.TimeoutExpired) as error:
            print(f"compile-failed: {error}", file=sys.stderr)
            return 2
        warnings = len(re.findall(r"RESOURCE COMPILE WARNING:", compiled.stdout + compiled.stderr))
        append_ledger(
            {
                "at": utc(),
                "command": "compile",
                "result": "pass" if compiled.returncode == 0 else "fail",
                "returncode": compiled.returncode,
                "argv": compiled.command,
                "warnings": warnings,
                "stage": str(Path(args.out)),
                "addon": addon,
                "log": str(compiled.log),
                "output": str(compiled.output) if compiled.output else "",
                "compiled_files": [str(path) for path in compiled.compiled_files],
                "content_addon": str(compiled.content_addon) if compiled.content_addon else "",
                "game_addon": str(compiled.game_addon) if compiled.game_addon else "",
            }
        )
        print(f"compile returncode {compiled.returncode} files {len(compiled.compiled_files)} warnings {warnings}")
        if compiled.returncode != 0:
            print((compiled.stdout + "\n" + compiled.stderr)[-4000:], file=sys.stderr)
            return compiled.returncode
    return 0


def cmd_mods(args: argparse.Namespace) -> int:
    try:
        since = date.fromisoformat(args.since) if args.since else None
        until = date.fromisoformat(args.until) if args.until else None
    except ValueError as error:
        print(f"mods-failed: {error}", file=sys.stderr)
        return 2
    result = oldmod_inventory(
        [Path(root).expanduser() for root in args.root],
        since=since,
        until=until,
        max_depth=args.depth,
    )
    for mod in result.mods:
        cloth = ",".join(mod.cloth_sections) or "none"
        hero = mod.hero or "unknown"
        print(f"{mod.modified}  {mod.kind:5}  {hero:22}  {cloth:26}  {mod.bytes:>10}  {mod.path}")
    counts = result.counts()
    print(
        f"packages={counts['packages']} addons={counts['addons']} vpks={counts['vpks']} "
        f"with_cloth={counts['with_cloth_sections']} skipped_game_paks={counts['skipped_game_paks']}"
    )
    for name, count in result.cloth_types().items():
        print(f"cloth-type {name} {count}")
    for failure in result.skipped_unreadable:
        print(f"skipped {failure}", file=sys.stderr)
    path = result.save(Path(args.report))
    print(f"receipt {path}")
    append_ledger(
        {
            "at": utc(),
            "command": "mods",
            "result": "pass",
            "roots": result.roots,
            "since": result.since,
            "until": result.until,
            "counts": counts,
            "cloth_types": result.cloth_types(),
            "receipt": str(path),
        }
    )
    return 0


def cmd_gate(args: argparse.Namespace) -> int:
    checks = gate_checks()
    previous = {}
    if GATE_STATE.is_file():
        previous = json.loads(GATE_STATE.read_text(encoding="utf-8"))
    regressions = [
        name for name, ok, _ in checks if previous.get(name) == "pass" and not ok
    ]
    state = {name: "pass" if ok else "fail" for name, ok, _ in checks}
    GATE_STATE.parent.mkdir(parents=True, exist_ok=True)
    GATE_STATE.write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
    write_status(checks)
    failed = [name for name, ok, _ in checks if not ok]
    append_ledger(
        {
            "at": utc(),
            "command": "gate",
            "result": "pass" if not failed else "fail",
            "checks": state,
            "regressions": regressions,
        }
    )
    for name, ok, detail in checks:
        print(f"[{'PASS' if ok else 'FAIL'}] {name}")
        if not ok and detail:
            print(detail)
    if regressions:
        print(f"ratchet-regression: {', '.join(regressions)}", file=sys.stderr)
        return 2
    return 0 if not failed else 1


def cmd_status(args: argparse.Namespace) -> int:
    if not GATE_STATE.is_file():
        print("no gate state; run gate first", file=sys.stderr)
        return 2
    state = json.loads(GATE_STATE.read_text(encoding="utf-8"))
    checks = [(name, value == "pass", "") for name, value in state.items()]
    write_status(checks)
    print(STATUS)
    return 0


def cmd_selftest(args: argparse.Namespace) -> int:
    """Exercise the gate's negative controls in a temporary copy."""
    failures = []
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp) / "repo"
        shutil.copytree(
            ROOT,
            root,
            ignore=shutil.ignore_patterns(".git", "artifacts", "dist", "__pycache__", "*.pyc"),
        )
        bad = root / "forge" / "_bad.py"
        # Built at runtime so this negative control does not itself trip the source scan.
        bad.write_text("def parse_" + "kv3():\n    return None\n", encoding="utf-8")
        result = subprocess.run(
            [sys.executable, "tools/project.py", "gate"],
            cwd=root,
            capture_output=True,
            text=True,
        )
        if result.returncode == 0:
            failures.append("gate accepted a kv3 parser")
        if bad.exists():
            bad.unlink()
        result = subprocess.run(
            [sys.executable, "tools/project.py", "gate"],
            cwd=root,
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            failures.append(f"gate failed a clean copy: {result.stderr[-500:]}")
    if failures:
        print("\n".join(failures), file=sys.stderr)
        return 2
    print("selftest: gate rejected the kv3 parser and passed the clean copy")
    return 0


